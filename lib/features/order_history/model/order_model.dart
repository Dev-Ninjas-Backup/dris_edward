class Order {
  final String restaurantName;
  final String restaurantImage;
  final String status;
  final String date;
  final String time;
  final String totalAmount;

  Order({
    required this.restaurantName,
    required this.restaurantImage,
    required this.status,
    required this.date,
    required this.time,
    required this.totalAmount,
  });
}
